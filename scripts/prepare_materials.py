"""Build shared report/slide numbers and an audited chart from recorded runs.

Figure ledger: one bar is one recorded complete attempt; height is SDK total
tokens in millions. Gray is the teammate reference, green the historical successful
local attempt, and coral the failed attempts. All bars share a zero baseline.
These are single observations with different settings, not a controlled ablation.
"""

import argparse
import json
from pathlib import Path
import subprocess
import sys

SOURCE = Path(__file__).resolve().parents[1]
LAB = SOURCE.parent


def escape(value):
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(char, char) for char in str(value))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lab-dir", type=Path, default=LAB)
    parser.add_argument("--no-figures", action="store_true")
    args = parser.parse_args()
    lab = args.lab_dir.resolve()
    evidence = SOURCE / "docs/experiments"
    records = json.loads((evidence / "call-metrics.json").read_text())
    records += json.loads((evidence / "optg-metrics.json").read_text())
    runs = {Path(item["log"]).parent.name: item for item in records}
    names = ["baseline-teammate", "opt-1101", "optf-1101", "optg2-1101"]
    prefixes = ["Baseline", "Initial", "Cache", "Feedback"]
    generated = lab / "report/generated"
    generated.mkdir(parents=True, exist_ok=True)
    commands = []
    summary = []
    for name, prefix in zip(names, prefixes, strict=True):
        record = runs[name]
        total = record["totals"]
        stage = next(v for k, v in record["stages"].items() if k.startswith("Stage 12"))
        values = {
            "Total": total["total_tokens"],
            "Input": total["prompt_tokens"],
            "Output": total["completion_tokens"],
            "Calls": total["calls"],
            "Reasoning": total["reasoning_tokens"],
            "StageInput": stage["prompt_tokens"],
            "StageTotal": stage["total_tokens"],
            "StageCalls": stage["calls"],
            "StageMean": round(stage["prompt_tokens"] / stage["calls"]),
        }
        for suffix, value in values.items():
            formatted = f"{value:,}".replace(",", "{,}")
            commands.append(
                r"\newcommand{" + chr(92) + prefix + suffix + "}{" + formatted + "}"
            )
        for suffix, value in {
            "CacheRate": total["input_cache_hit_ratio"],
            "StageCacheRate": stage["input_cache_hit_ratio"],
        }.items():
            commands.append(
                r"\newcommand{"
                + chr(92)
                + prefix
                + suffix
                + "}{"
                + f"{value * 100:.1f}"
                + r"\%}"
            )
        summary.append(
            {
                "run": name,
                "total_tokens": total["total_tokens"],
                "input_cache_hit_ratio": total["input_cache_hit_ratio"],
                "stage12_cache_hit_ratio": stage["input_cache_hit_ratio"],
            }
        )
    revision = subprocess.check_output(
        ["git", "rev-parse", "--short", "HEAD"], cwd=SOURCE, text=True
    ).strip()
    commands.append(r"\newcommand{\SourceRevision}{" + revision + "}")
    (generated / "metrics.tex").write_text(
        "% Generated by source/scripts/prepare_materials.py\n"
        + "\n".join(commands)
        + "\n"
    )
    changes = json.loads((evidence / "change-effects.json").read_text())["changes"]
    rows = [
        " & ".join(
            escape(item[key]) for key in ("id", "title", "change", "effect", "status")
        )
        + " "
        + chr(92) * 2
        for item in changes
    ]
    table = (
        r"""\begingroup\small\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.13}
\begin{longtable}{p{0.5cm}p{2.25cm}p{4.1cm}p{6.6cm}p{1.65cm}}
\toprule
ID & 工作项 & 实际修改 & 效果与证据限制 & 状态\\\midrule
\endfirsthead
\toprule ID & 工作项 & 实际修改 & 效果与证据限制 & 状态\\\midrule\endhead
"""
        + "\n".join(rows)
        + r"""
\bottomrule
\end{longtable}
\endgroup
"""
    )
    (generated / "change-table.tex").write_text(table)
    (generated / "run-summary.json").write_text(
        json.dumps({"source_revision": revision, "runs": summary}, indent=2) + "\n"
    )
    if args.no_figures:
        return
    sys.path.insert(0, str(SOURCE / "scripts/vendor"))
    import fvstyle as fv
    import matplotlib.pyplot as plt

    current = fv.apply_rc("paper")
    fig, ax = plt.subplots(figsize=(8.0, 4.2))
    values = [runs[name]["totals"]["total_tokens"] / 1e6 for name in names]
    colors = [fv.HUES["vgray"], fv.HUES["vgreen"], fv.HUES["vcoral"], fv.HUES["vcoral"]]
    bars = ax.bar(
        ["Teammate\nGREEN", "Initial\nGREEN", "OPT-F\nFAILED", "OPT-G2\nFAILED"],
        values,
        color=colors,
        width=0.58,
    )
    ax.set_ylabel("Recorded SDK tokens (millions)")
    ax.set_xlabel("Single recorded attempts")
    ax.set_ylim(0, 2.6)
    for bar, value in zip(bars, values, strict=True):
        ax.text(
            bar.get_x() + bar.get_width() / 2,
            value + 0.09,
            f"{value:.3f}",
            ha="center",
            color=fv.NEUTRALS["vink"],
            fontsize=11,
        )
    fv.apply_frame(ax, current.frame)
    fv.apply_grid(ax, current.grid)
    fig.subplots_adjust(left=0.13, right=0.98, top=0.94, bottom=0.25)
    fig.text(
        0.5,
        0.035,
        "Settings differ; failed attempts are incomplete; no causal speedup claim.",
        ha="center",
        fontsize=9,
        color=fv.NEUTRALS["baseline"],
    )
    problems = fv.audit(fig)
    errors = []
    for problem in problems:
        rule, _, message = problem.partition(" ")
        severity = fv.RENDER_RULES.get(rule, "error")
        print(f"{severity} {rule}: {message}")
        if severity == "error":
            errors.append(problem)
    if errors:
        raise ValueError("Figure audit failed")
    assets = lab / "report/assets"
    assets.mkdir(exist_ok=True)
    fv.save(fig, assets / "token-attempts.pdf")
    fv.save(fig, assets / "token-attempts.png")
    (generated / "figure-audit.json").write_text(
        json.dumps({"audit_called": True, "problems": problems}, indent=2) + "\n"
    )


if __name__ == "__main__":
    main()
